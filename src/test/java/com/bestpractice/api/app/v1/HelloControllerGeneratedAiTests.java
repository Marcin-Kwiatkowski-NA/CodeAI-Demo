import org.springframework.web.context.WebApplicationContext;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
public class HelloControllerGeneratedAiTests {

    @Autowired
    private WebApplicationContext webApplicationContext;

    private MockMvc mockMvc;

    @BeforeEach
    void setUp() {
        mockMvc = MockMvcBuilders.webAppContextSetup(webApplicationContext).build();
    }

    @Test
    void givenValidRequest_whenGetHelloEndpoint_thenReturnsHelloWorld() throws Exception {
        // GIVEN: A valid request to the /api/v1/hello endpoint

        // WHEN: The request is performed
        mockMvc.perform(get("/api/v1/hello")
                .accept(MediaType.APPLICATION_JSON))
                // THEN: The response contains the expected "Hello world." message
                .andExpect(status().isOk())
                .andExpect(content().json("{\"key\":\"Hello world.\"}"));
    }
}
